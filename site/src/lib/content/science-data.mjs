/* CHY102 and PCS211: course records written for this site from the Fall 2026 course outlines (not vendored; the
   old site never had these courses). Same shape as the math records in vendor/course-data.mjs, so the guides share
   one model, plus what these outlines need:

   - Every assessment carries its own `weightLabel`, `prep` (the preparation checklist; its order defines the saved
     check keys `${id}-${i}`, so never reorder it) and `rules`.
   - Dated work: `date` + `time` (+ `end`). Homework is due at `time` ("Due"); a test starts at `time`.
   - `window: { start, end }`: work in a published span whose exact day is not in the outline (PCS211 labs and
     tutorials run every other week; CHY102 exam wrappers are due during a week). No time is ever invented.
   - No `date` and no `window`: pending (the final) or listed without a date (`timingText`).
   - `grades`: the outline's grading, as categories of items. `variants` are alternative weight tables over the
     same items (`pick: 'choose'` for a scheme the student is enrolled in, `'best'` when the course applies the
     higher result automatically). `requirements` are extra minimums; `bonus` adds to the course grade.

   Facts only from the outlines; anything they leave open says so and points to D2L. */

